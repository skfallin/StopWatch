"""Generate the embedded, antialiased VLW subsets used by Orbita (Pillow only)."""
from pathlib import Path
import struct
from PIL import ImageFont

root = Path(__file__).resolve().parents[1]
source = root / "assets/fonts/InterVariable.ttf"
sizes = (18, 22, 28, 36, 68, 96)
output = ["// Generated by tools/generate_ui_fonts.py. Inter: SIL Open Font License; see assets/fonts/OFL.txt.\n#pragma once\n#include <Arduino.h>\nnamespace ui_fonts {\n"]
for size in sizes:
    font = ImageFont.truetype(str(source), size)
    axes = font.get_variation_axes()
    font.set_variation_by_axes([400 if a["name"] == b"Weight" else min(32, a["maximum"]) for a in axes])
    chars = sorted(set(range(32, 127)) | set(range(160, 256)) | {0x2013, 0x2014, 0x2019, 0x2026})
    if size >= 68:
        chars = sorted(set(map(ord, " 0123456789:%-+./ONFs")))
    metrics, bitmaps = [], []
    for code in chars:
        mask, (left, top) = font.getmask2(chr(code), mode="L", anchor="ls")
        width, height = mask.size
        advance = round(font.getlength(chr(code)))
        assert 0 <= width <= 255 and 0 <= advance <= 255 and -128 <= left <= 127
        pixels = bytes(mask)
        assert len(pixels) == width * height
        metrics.append((code, height, width, advance, -top, left, 0))
        bitmaps.append(pixels)
    ascent = max(m[4] for m in metrics)
    descent = max(m[1] - m[4] for m in metrics)
    data = struct.pack(">6i", len(chars), 11, size, 0, ascent, descent)
    data += b"".join(struct.pack(">7i", *m) for m in metrics)
    data += b"".join(bitmaps)
    # M5GFX searches a sorted UTF-16 index and reads each bitmap within its bounds.
    assert all(a < b for a, b in zip(chars, chars[1:]))
    assert 24 + len(chars) * 28 + sum(len(b) for b in bitmaps) == len(data)
    output.append(f"const uint8_t inter{size}[] PROGMEM = {{\n")
    output.extend("  " + ",".join(f"0x{b:02x}" for b in data[i:i+24]) + ",\n" for i in range(0, len(data), 24))
    output.append("};\n")
    print(f"Inter {size}: {len(chars)} glyphs, {len(data)} bytes")
output.append("}\n")
(root / "src/ui_fonts.h").write_text("".join(output))
