"""Generate firmware lookup and native iOS catalogs from reviewed translations."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    pairs = json.loads((ROOT / 'locales/en.json').read_text())
    cpp = lambda s: json.dumps(s, ensure_ascii=False)
    used = set()
    for path in [*(ROOT / 'src').glob('*.cpp'), *(ROOT / 'src').glob('*.h'), *(ROOT / 'include').glob('*.h')]:
        if path.name == 'i18n.h': continue
        used.update(re.findall(r'i18n::text\("([^"\n]*)"\)', path.read_text()))
    # Constant label tables are translated at the point of use.
    for name in ['src/main.cpp', 'src/clock_view.cpp', 'src/scene_view.cpp',
                 'include/ui_theme.h', 'include/ui_sounds.h', 'include/clock_model.h']:
        used.update(re.findall(r'"([^"\n]*)"', (ROOT / name).read_text()))
    entries = [(key, pairs[key]) for key in sorted(used) if key in pairs]
    header = '''// Generated by tools/generate_localizations.py. Edit locales/en.json.
#pragma once
#include <algorithm>
#include <atomic>
#include <string_view>

namespace i18n {
inline std::atomic<bool> italian{false};
struct Translation { const char* key; const char* english; };
inline constexpr Translation translations[]={
'''
    header += ''.join('    {' + cpp(k) + ',' + cpp(v) + '},\n' for k, v in entries)
    header += '''};
inline const char* text(const char* key) {
    if(italian.load(std::memory_order_relaxed)) return key;
    const std::string_view value(key);
    const auto* end=translations+sizeof(translations)/sizeof(translations[0]);
    const auto* found=std::lower_bound(translations,end,value,
        [](const Translation& entry,std::string_view item) { return std::string_view(entry.key)<item; });
    return found!=end && value==found->key?found->english:key;
}
}
'''
    result = {ROOT / 'include/i18n.h': header}
    # Swift's compiler turns interpolations into printf-style localization keys.
    # These entries are checked against compiler output during verification.
    formats = {
        r'Si spegne dopo \(draft.screenTimeout) secondi': ('Si spegne dopo %lld secondi', 'Turns off after %lld seconds'),
        r'Preferiti · \(draft.favorites.count)/8': ('Preferiti · %lld/8', 'Favorites · %lld/8'),
        r'Wi-Fi non riuscito: \(issue) Invio tramite Bluetooth.': ('Wi-Fi non riuscito: %@ Invio tramite Bluetooth.', 'Wi-Fi failed: %@ Sending over Bluetooth.'),
        r'Ponte StopWatch \(event.kind.rawValue)': ('Ponte StopWatch %@', 'StopWatch bridge %@'),
        r'Trasferimento Wi-Fi: HTTP \(http.statusCode).': ('Trasferimento Wi-Fi: HTTP %lld.', 'Wi-Fi transfer: HTTP %lld.'),
    }
    catalogs = {'en': {}, 'it': {}}
    for key, value in pairs.items():
        if r'\(' in key:
            if key not in formats: raise ValueError('Missing interpolation format: ' + key)
            key, value = formats[key]
        key, value = key.replace(r'\n', '\n'), value.replace(r'\n', '\n')
        catalogs['en'][key] = value
        catalogs['it'][key] = key
    for language, entries in catalogs.items():
        result[ROOT / f'ios/StopWatch/{language}.lproj/Localizable.strings'] = '// Generated by tools/generate_localizations.py.\n' + ''.join(
            f'{cpp(k)} = {cpp(v)};\n' for k, v in sorted(entries.items()))
    import html
    portal = (ROOT / 'web/portal.html').read_text()
    keys = set(html.unescape(key) for key in re.findall(r'data-i18n="([^"]+)"', portal))
    keys.update(re.findall(r"tr\('([^']+)'", portal))
    # Include labels held in JavaScript tables and translated through tr(variable).
    keys.update(key for key in re.findall(r"'([^'\n]*)'", portal) if key in pairs)
    missing = keys - pairs.keys()
    if missing: raise ValueError('Missing portal translations: ' + repr(missing))
    catalog = {key: pairs[key] for key in sorted(keys)}
    portal = portal.replace('/* TRANSLATIONS */', json.dumps(catalog, ensure_ascii=False))
    result[ROOT / 'src/portal_page.h'] = '// Generated by tools/generate_localizations.py. Edit web/portal.html.\n#pragma once\nconst char portalPage[] PROGMEM = R"HTML(' + portal + ')HTML";\n'
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Outdated localization: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != content:
                path.write_text(content)
